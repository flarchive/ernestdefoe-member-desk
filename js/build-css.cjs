/*
 * Compiles the forum page's styles (less/forum-chunk.less) into a JS module that ships inside the
 * lazy staff chunk, so forum.css (which every visitor downloads) carries none of Member Desk.
 * The admin keeps its own stylesheet (less/admin.less): only admins load admin.css.
 */
const fs = require('fs');
const path = require('path');
const less = require('less');

const src = path.resolve(__dirname, '../less/forum-chunk.less');
const out = path.resolve(__dirname, 'src/forum/components/deskCss.generated.ts');

less
  .render(fs.readFileSync(src, 'utf8'), { filename: src })
  .then(({ css }) => {
    const min = css
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/\s+/g, ' ')
      .replace(/\s*([{};,>])\s*/g, '$1')
      .replace(/;}/g, '}')
      .trim();
    fs.writeFileSync(out, `// Generated by build-css.cjs from less/forum-chunk.less. Do not edit.\nexport default ${JSON.stringify(min)};\n`);
    console.log(`deskCss: ${min.length} bytes`);
  })
  .catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
